// More isometric figures for the new tab, drawn with the Anatomy kit
// (vendor/anatomy, MIT). Each is a small real object whose moving part shows
// live data: a pocket watch (the time), a weather station (wind and
// temperature), a two-cube desk calendar (today), a receipt spike (tasks
// done) and a sticky-note pad (notes). Static art is built here once; the
// page moves the few parts that change.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as k from '../vendor/anatomy/iso-kit.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const S = (paths, style) => k.solidSvg(paths, style);
const L = (d, style) => k.lineSvg(d, style);
const D = (points, style) => k.dotsSvg(points, style);
const circle = (cx, cy, r, z, n = 24) => Array.from({ length: n }, (_, i) => [cx + r * Math.cos((i / n) * Math.PI * 2), cy + r * Math.sin((i / n) * Math.PI * 2), z]);

async function emit(name, data) {
  const body = Object.entries(data)
    .map(([key, v]) => `  ${key}: ${JSON.stringify(v)},`)
    .join('\n');
  const ts = `// GENERATED by scripts/build-figures-more.mjs with the Anatomy kit (vendor/anatomy, MIT). Do not edit.\nexport const ${name.toUpperCase()} = {\n${body}\n} as const;\n`;
  await writeFile(path.join(root, `src/ui/figures/${name}.ts`), ts);
  console.log(`${name}:`, Math.round(ts.length / 1024), 'KB');
}

// ------------------------------------------------------------ pocket watch

{
  const W = 200;
  const H = 150;
  const BASE_R = 44;
  const BASE_H = 7;
  const CASE_R = 30;
  const CASE_Z = BASE_H;
  const CASE_H = 8;
  const BEZEL_H = 2.4;
  const FACE = CASE_Z + CASE_H + BEZEL_H;
  const SUB = [0, 13];
  const P = k.fitProjection([...circle(0, 0, BASE_R, -2), ...circle(0, 0, BASE_R, 0), [0, -CASE_R - 17, CASE_Z + 6], [0, 0, FACE + 2]], W, H, { pad: 6, azimuth: 40 });
  const at = (p) => k.iso(p, P);
  const out = [];
  // Turned base on a felt ring, with a groove and four screws.
  out.push(S(k.cylinder(0, 0, BASE_R, -2, 2, P, 72), { tone: 'lo' }));
  out.push(S(k.cylinder(0, 0, BASE_R - 1.5, 0, BASE_H, P, 72, 1), { tone: 'mid' }));
  out.push(L(k.ring(0, 0, BASE_R - 5, BASE_H, P, 72), { tone: 'lo' }));
  const screws = [45, 135, 225, 315].map((a) => [Math.cos((a * Math.PI) / 180) * (BASE_R - 9), Math.sin((a * Math.PI) / 180) * (BASE_R - 9)]);
  out.push(L(screws.map(([x, y]) => k.ring(x, y, 1.8, BASE_H, P, 14)).join(''), { tone: 'lo' }));
  out.push(D(screws.map(([x, y]) => at([x, y, BASE_H])), { size: 0.45 }));
  // Bow, pendant and crown at twelve o'clock (behind the case from here).
  const bowY = -CASE_R - 12;
  out.push(L(k.ring(0, bowY, 6.4, CASE_Z + 4, P, 40) + k.ring(0, bowY, 4.6, CASE_Z + 4, P, 40), { tone: 'mid' }));
  out.push(S(k.cylinder(0, -CASE_R - 5.2, 3.4, CASE_Z + 1.4, 5, P, 28, 0.5), { tone: 'hi' }));
  out.push(L(k.knurl(0, -CASE_R - 5.2, 3.4, CASE_Z + 2, CASE_Z + 6, 18, P, 0.2), { tone: 'lo' }));
  out.push(S(k.cylinder(0, -CASE_R - 1.4, 2.2, CASE_Z + 2.2, 3.4, P, 20), { tone: 'mid' }));
  // Case, fluted bezel and dial.
  out.push(S(k.cylinder(0, 0, CASE_R, CASE_Z, CASE_H, P, 80, 0.8), { tone: 'hi', crease: 'lo' }));
  out.push(L(k.sideArc(0, 0, CASE_R, CASE_Z + 3.2, P, 48), { tone: 'faint' }));
  out.push(S(k.cylinder(0, 0, CASE_R + 0.4, CASE_Z + CASE_H, BEZEL_H, P, 80, 0.5), { tone: 'hi' }));
  out.push(L(k.knurl(0, 0, CASE_R + 0.4, CASE_Z + CASE_H + 0.3, FACE - 0.3, 90, P, 0.2), { tone: 'lo' }));
  out.push(L(k.ring(0, 0, CASE_R - 1.8, FACE, P, 80), { tone: 'lo' }));
  const minutes = k.radialTicks(0, 0, CASE_R - 3, 60, 5, FACE, [1.1, 3], P);
  out.push(L(minutes.minor, { tone: 'lo' }), L(minutes.major, { tone: 'mid' }));
  out.push(L(k.lineOnTop([0, -(CASE_R - 3)], [0, -(CASE_R - 7.2)], FACE, P), { tone: 'hi' }));
  out.push(L(k.ring(0, 0, CASE_R - 8, FACE, P, 64), { tone: 'faint' }));
  // Small seconds at six o'clock.
  out.push(L(k.ring(SUB[0], SUB[1], 6.6, FACE, P, 36), { tone: 'lo' }));
  const subTicks = k.radialTicks(SUB[0], SUB[1], 6.2, 12, 3, FACE, [0.9, 1.8], P);
  out.push(L(subTicks.minor, { tone: 'faint' }), L(subTicks.major, { tone: 'lo' }));
  const cap = [S(k.cylinder(0, 0, 1.9, FACE, 0.9, P, 18), { tone: 'hi' }), D([at([0, 0, FACE + 0.9])], { size: 0.5, tone: 'hi' }), D([at([SUB[0], SUB[1], FACE + 0.2])], { size: 0.55, tone: 'hi' })].join('');
  await emit('watch', { width: W, height: H, projection: P, face: FACE + 0.2, sub: SUB, hour: [3.2, 13], minute: [4, 22.5], second: [1.4, 5.8], below: out.join(''), above: cap });
}

// ------------------------------------------------------------ weather station

{
  const W = 220;
  const H = 172;
  const PLATE = { x: -52, y: -36, w: 104, d: 72, r: 6 };
  const MAST = [-18, -8];
  const MAST_TOP = 74;
  const VANE_Z = 57;
  const CUP_Z = 77;
  const THERMO = { x: 14, y: 6, w: 13, d: 4, r: 1 };
  const T_X = THERMO.x + 8.4;
  const T_Y = THERMO.y + THERMO.d + 1.6;
  const T_LOW = 9;
  const T_HIGH = 50;
  const GAUGE = [34, -18];
  const P = k.fitProjection([...k.boxCorners(PLATE, -4, 0), [MAST[0] + 18, MAST[1] + 18, CUP_Z + 3], [MAST[0] - 18, MAST[1] - 18, CUP_Z + 3], [MAST[0], MAST[1], MAST_TOP + 6], [THERMO.x + THERMO.w, THERMO.y + THERMO.d, 56]], W, H, { pad: 8, azimuth: 38 });
  const at = (p) => k.iso(p, P);
  const base = [];
  for (const [x, y] of k.corners(PLATE, 10)) base.push(S(k.cylinder(x, y, 4.5, -4, 4, P, 20), { tone: 'lo' }));
  base.push(S(k.slabOf(PLATE, 0, 5, P, 8, 1), { tone: 'mid' }));
  base.push(L(k.planOutline(k.insetPlan(PLATE, 4), 5, P), { tone: 'lo' }));
  const screws = k.corners(PLATE, 7);
  base.push(D(screws.map(([x, y]) => at([x, y, 5])), { size: 0.45 }));
  // Compass rose around the mast foot: north is engraved.
  const rose = k.radialTicks(MAST[0], MAST[1], 13, 16, 4, 5, [1.4, 3.4], P);
  base.push(L(k.ring(MAST[0], MAST[1], 13, 5, P, 48), { tone: 'faint' }), L(rose.minor, { tone: 'faint' }), L(rose.major, { tone: 'lo' }));
  base.push(k.faceTextSvg(k.topMatrix([MAST[0] - 1.4, MAST[1] - 15.4], 5, P, 'x'), 'N', { size: 3.6, tone: 'mid' }));
  // Mast with a flange, a collar for the vane and a hub for the cups.
  base.push(S(k.cylinder(MAST[0], MAST[1], 5.5, 5, 2, P, 32, 0.4), { tone: 'mid' }));
  base.push(D([0, 90, 180, 270].map((a) => at([MAST[0] + Math.cos((a * Math.PI) / 180) * 4, MAST[1] + Math.sin((a * Math.PI) / 180) * 4, 7])), { size: 0.4 }));
  base.push(S(k.cylinder(MAST[0], MAST[1], 1.7, 7, VANE_Z - 7, P, 16), { tone: 'hi', crease: 'none' }));
  base.push(S(k.cylinder(MAST[0], MAST[1], 2.8, VANE_Z - 2, 3, P, 24, 0.4), { tone: 'mid' }));
  const mastUpper = S(k.cylinder(MAST[0], MAST[1], 1.5, VANE_Z + 1, MAST_TOP - VANE_Z - 1, P, 16), { tone: 'hi', crease: 'none' }) + S(k.cylinder(MAST[0], MAST[1], 3, MAST_TOP, 3, P, 24, 0.5), { tone: 'mid' });
  // Rain gauge, back right: a funnel on a can.
  const gauge = [];
  gauge.push(S(k.cylinder(GAUGE[0], GAUGE[1], 6.4, 5, 16, P, 40, 0.6), { tone: 'hi' }));
  gauge.push(L(k.sideArc(GAUGE[0], GAUGE[1], 6.4, 10, P, 24) + k.sideArc(GAUGE[0], GAUGE[1], 6.4, 15, P, 24), { tone: 'faint' }));
  gauge.push(S(k.cylinder(GAUGE[0], GAUGE[1], 7.4, 21, 2, P, 40, 0.5), { tone: 'hi' }));
  gauge.push(L(k.ring(GAUGE[0], GAUGE[1], 5.6, 23, P, 32) + k.ring(GAUGE[0], GAUGE[1], 2.2, 23, P, 16), { tone: 'lo' }));
  // Thermometer on a board: the scale on the board, the tube and bulb in front.
  const thermo = [];
  thermo.push(S(k.slabOf(THERMO, 5, 50, P, 3, 0.5), { tone: 'hi', crease: 'lo' }));
  for (let i = 0; i <= 20; i++) {
    const z = T_LOW + ((T_HIGH - T_LOW) * i) / 20;
    thermo.push(L(k.segment([THERMO.x + 1.4, THERMO.y + THERMO.d, z], [THERMO.x + (i % 5 ? 3.4 : 5), THERMO.y + THERMO.d, z], P), { tone: i % 5 ? 'faint' : 'lo' }));
  }
  thermo.push(D([at([THERMO.x + 6.5, THERMO.y + THERMO.d, 52]), at([THERMO.x + 6.5, THERMO.y + THERMO.d, 8])], { size: 0.4 }));
  thermo.push(S(k.cylinder(T_X, T_Y, 2.6, 5.6, 4, P, 20), { tone: 'hi' }));
  thermo.push(S(k.cylinder(T_X, T_Y, 1.25, 9.4, T_HIGH - 7, P, 14), { tone: 'hi', crease: 'none' }));
  await emit('station', {
    width: W,
    height: H,
    projection: P,
    mast: MAST,
    vaneZ: VANE_Z,
    cupZ: CUP_Z,
    thermo: { x: T_X, y: T_Y + 1.3, low: T_LOW, high: T_HIGH, bulb: 7 },
    back: base.join(''),
    mastUpper,
    gauge: gauge.join(''),
    thermoSvg: thermo.join(''),
  });
}

// ------------------------------------------------------------ two-cube desk calendar

{
  const W = 170;
  const H = 116;
  const STAND = { x: -40, y: -14, w: 80, d: 30, r: 3 };
  const CUBE = 17;
  const CUBES = [
    { x: -34, y: -9 },
    { x: -15, y: -9 },
  ];
  const MONTH = { x: 6, y: -9, w: 28, d: 17, r: 1.2 };
  const P = k.fitProjection([...k.boxCorners(STAND, -2, 0), [CUBES[0].x, CUBES[0].y, 5 + CUBE + 1], [MONTH.x + MONTH.w, MONTH.y + MONTH.d, 5 + 9]], W, H, { pad: 6, azimuth: 36 });
  const out = [];
  out.push(S(k.slabOf(STAND, -2, 2, P, 6), { tone: 'lo' }));
  out.push(S(k.slabOf(k.insetPlan(STAND, 1), 0, 5, P, 6, 0.6), { tone: 'mid' }));
  out.push(L(k.planOutline(k.insetPlan(STAND, 3.5), 5, P), { tone: 'faint' }));
  const faces = [];
  for (const c of CUBES) {
    const plan = { x: c.x, y: c.y, w: CUBE, d: CUBE, r: 1.4 };
    out.push(S(k.slabOf(plan, 5, CUBE, P, 4, 0.8), { tone: 'hi', crease: 'lo' }));
    // The day digit sits on the front face; a faint one on the side, like the real cubes.
    // The day digit's baseline sits low on the front face so the glyph is centred on it.
    faces.push(k.sideMatrix([c.x + CUBE / 2, c.y + CUBE], 5 + 4.4, P, 'left'));
  }
  out.push(S(k.slabOf(MONTH, 5, 9, P, 3, 0.6), { tone: 'hi', crease: 'lo' }));
  out.push(L(k.lineOnTop([MONTH.x + 2, MONTH.y + 3], [MONTH.x + MONTH.w - 2, MONTH.y + 3], 14, P), { tone: 'faint' }));
  await emit('cubes', {
    width: W,
    height: H,
    projection: P,
    art: out.join(''),
    dayFaces: faces,
    monthFace: k.sideMatrix([MONTH.x + MONTH.w / 2, MONTH.y + MONTH.d], 5 + 2.4, P, 'left'),
    weekdayFace: k.topMatrix([MONTH.x + MONTH.w / 2, MONTH.y + 9.6], 14, P, 'x'),
  });
}

// ------------------------------------------------------------ receipt spike (to-do)

{
  const W = 120;
  const H = 150;
  const BASE_R = 15;
  const SLIPS = 8;
  const STEP = 3.6;
  const TOP = 6 + SLIPS * STEP + 14;
  const P = k.fitProjection([...circle(0, 0, BASE_R, 0), ...circle(0, 0, 17, 6 + SLIPS * STEP), [0, 0, TOP + 3]], W, H, { pad: 6, azimuth: 40 });
  const at = (p) => k.iso(p, P);
  const base = [];
  base.push(S(k.cylinder(0, 0, BASE_R, 0, 3, P, 48, 0.6), { tone: 'mid' }));
  base.push(L(k.knurl(0, 0, BASE_R, 0.6, 2.6, 60, P, 0.2), { tone: 'lo' }));
  base.push(S(k.cylinder(0, 0, BASE_R - 3, 3, 1.6, P, 40, 0.5), { tone: 'mid' }));
  base.push(L(k.ring(0, 0, BASE_R - 6, 4.6, P, 32), { tone: 'faint' }));
  const spike = (z0, z1) => S(k.cylinder(0, 0, 0.75, z0, z1 - z0, P, 12), { tone: 'hi', crease: 'none' });
  const slips = [];
  const segs = [];
  let z = 4.6;
  for (let i = 0; i < SLIPS; i++) {
    const top = 6 + i * STEP;
    segs.push(spike(z, top));
    z = top + 0.5;
    const a = (((i * 47) % 60) - 30) * (Math.PI / 180);
    const corners = k.roundedPlan({ x: -13, y: -8, w: 26, d: 16, r: 0.8 }, 3).map(([x, y]) => [x * Math.cos(a) - y * Math.sin(a), x * Math.sin(a) + y * Math.cos(a)]);
    const slip = [S(k.extrude(corners, top, 0.5, P, { convex: true }), { tone: 'hi', crease: 'faint' })];
    for (const [n, yy] of [-4, -1, 2].entries()) {
      const x0 = -9;
      const x1 = 9 - n * 4;
      const p0 = [x0 * Math.cos(a) - yy * Math.sin(a), x0 * Math.sin(a) + yy * Math.cos(a)];
      const p1 = [x1 * Math.cos(a) - yy * Math.sin(a), x1 * Math.sin(a) + yy * Math.cos(a)];
      slip.push(L(k.lineOnTop(p0, p1, top + 0.5, P), { tone: 'faint', free: 'end' }));
    }
    slip.push(D([at([0, 0, top + 0.5])], { size: 0.5, tone: 'lo' }));
    slips.push(slip.join(''));
  }
  const tip = spike(z, TOP) + S(k.cylinder(0, 0, 0.45, TOP, 2.4, P, 10), { tone: 'hi', crease: 'none' }) + D([at([0, 0, TOP + 2.4])], { size: 0.4, tone: 'hi' });
  await emit('spike', { width: W, height: H, projection: P, base: base.join(''), segs, slips, tip });
}

// ------------------------------------------------------------ sticky-note pad

{
  const W = 150;
  const H = 104;
  const TRAY = { x: -36, y: -24, w: 72, d: 48, r: 4 };
  const PAD = { x: -28, y: -19, w: 36, d: 36, r: 1.4 };
  const PAD_H = 9;
  const P = k.fitProjection([...k.boxCorners(TRAY, -1, 0), [PAD.x, PAD.y, 3 + PAD_H + 1]], W, H, { pad: 6, azimuth: 40 });
  const out = [];
  out.push(S(k.slabOf(TRAY, -1, 4, P, 8, 0.8), { tone: 'mid' }));
  out.push(L(k.planOutline(k.insetPlan(TRAY, 3), 3, P), { tone: 'lo' }));
  out.push(S(k.slabOf(PAD, 3, PAD_H, P, 3, 0.3), { tone: 'hi', crease: 'faint' }));
  for (let z = 4.2; z < 3 + PAD_H - 0.6; z += 1.1) {
    out.push(L(k.segment([PAD.x + 1, PAD.y + PAD.d, z], [PAD.x + PAD.w - 1, PAD.y + PAD.d, z], P) + k.segment([PAD.x + PAD.w, PAD.y + 1, z], [PAD.x + PAD.w, PAD.y + PAD.d - 1, z], P), { tone: 'faint' }));
  }
  // The top sheet, a little askew; it carries the count.
  const top = 3 + PAD_H;
  const a = -4 * (Math.PI / 180);
  const sheet = k.roundedPlan({ x: -17, y: -17, w: 34, d: 34, r: 1.2 }, 3).map(([x, y]) => [-10 + x * Math.cos(a) - y * Math.sin(a), -1 + x * Math.sin(a) + y * Math.cos(a)]);
  out.push(S(k.extrude(sheet, top, 0.4, P, { convex: true }), { tone: 'hi', lit: true }));
  // A pen lying beside the pad, with its clip and tip.
  const pen = { x: 15, y: -20, w: 6, d: 40, r: 3 };
  out.push(S(k.slabOf(pen, 3, 5, P, 6, 0.4), { tone: 'hi', crease: 'lo' }));
  out.push(L(k.lineOnTop([pen.x, pen.y + 13], [pen.x + pen.w, pen.y + 13], 8, P), { tone: 'lo' }));
  out.push(S(k.slabOf({ x: pen.x + 2.2, y: pen.y + 2, w: 1.6, d: 10, r: 0.6 }, 8, 0.8, P, 3), { tone: 'mid' }));
  out.push(S(k.cylinder(pen.x + 3, pen.y + pen.d + 1.2, 1.6, 4.4, 2.2, P, 14), { tone: 'mid' }));
  await emit('pad', { width: W, height: H, projection: P, art: out.join(''), countFace: k.topMatrix([-10, 1], top + 0.4, P, 'x') });
}
